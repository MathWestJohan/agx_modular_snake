"""Copy the gait tables of the simulation into the robot firmware.

Writes firmware/snake_sensors/sim_gaits.h from the gait tables and thresholds in
snakeapp/gait_controller.py, so the robot runs exactly the gaits tuned in the simulation.

Run it after changing the gaits in the simulation, then upload snake_sensors again:
    python firmware/sync_from_sim.py
It only reads the Python file, so AGX does not have to be installed.
"""
import ast
import math
import os

FIRMWARE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(FIRMWARE)
GAIT_FILE = os.path.join(ROOT, 'snakeapp', 'gait_controller.py')
OUTPUT = os.path.join(FIRMWARE, 'snake_sensors', 'sim_gaits.h')

SITUATIONS = ['flat', 'uphill', 'downhill', 'crest', 'valley', 'maze']   # order of SimSituation
KEYS = ['am_p', 'am_y', 'phi_p', 'phi_y', 'phi_py', 'offset_p', 'offset_y']   # order of SimGait


def constants(path, names):
    """Evaluate the top-level assignments to `names` in a Python file without importing it."""
    tree = ast.parse(open(path, encoding='utf-8').read(), path)
    env = {'math': math, 'D': math.radians, 'dict': dict}
    values = {}
    for node in tree.body:
        if not isinstance(node, ast.Assign) or len(node.targets) != 1:
            continue
        target = node.targets[0]
        targets = target.elts if isinstance(target, ast.Tuple) else [target]
        here = [t.id for t in targets if isinstance(t, ast.Name)]
        if not any(n in names for n in here):
            continue
        value = eval(compile(ast.Expression(node.value), path, 'eval'), env)
        if isinstance(target, ast.Tuple):
            values.update(zip(here, value))
        else:
            values[here[0]] = value
    missing = [n for n in names if n not in values]
    if missing:
        raise SystemExit('{}: cannot find {}'.format(path, ', '.join(missing)))
    return values


def f(x):
    """A C++ float literal."""
    text = '{:.7g}'.format(round(float(x), 6) + 0.0)   # + 0.0 turns -0.0 into 0.0
    if not any(c in text for c in '.e'):
        text += '.0'   # 12 -> 12.0f (12f is not valid C++)
    return text + 'f'


def deg(x):
    return f(math.degrees(x))


def header():
    g = constants(GAIT_FILE, ['GAITS', 'SLOPE_ON', 'SLOPE_OFF', 'BEND_ON', 'BEND_OFF', 'MIN_DWELL'])
    lines = [
        '// SIM: generated by firmware/sync_from_sim.py from snakeapp/gait_controller.py.',
        '// Do not edit: change the simulation and run the script again.',
        '#pragma once',
        '',
        '// the gaits of the simulation ("situations")',
        'enum SimSituation { ' + ', '.join('SIT_' + s.upper() for s in SITUATIONS) + ', SIT_COUNT };',
        'static const char* const SIM_SITUATION_NAMES[SIT_COUNT] = {' + ', '.join('"{}"'.format(s) for s in SITUATIONS) + '};',
        '',
        '// One gait, angles in degrees:',
        '//   amP, amY       amplitude of the pitch / yaw joints (the sign only shifts the wave half a cycle)',
        '//   phiP, phiY     phase shift of the wave per two joints (pitch: + = from the tail to the head)',
        '//   phiPY          phase between the yaw wave and the pitch wave',
        '//   offsetP/Y      constant bend of the pitch / yaw joints (pitch: - = convex, like a hilltop)',
        'struct SimGait {',
        '  bool valid;   // false: this joint layout has no gait for this situation',
        '  float amP, amY, phiP, phiY, phiPY, offsetP, offsetY;',
        '};',
        'struct SimGaitTable {',
        '  const char* config;   // one letter per joint from the head: P pitch, Y yaw',
        '  SimGait gaits[SIT_COUNT];',
        '};',
        '',
        '// choosing the gait from the slope (degrees)',
        'const float SIM_SLOPE_ON_DEG = {}, SIM_SLOPE_OFF_DEG = {};   // uphill / downhill above ON, flat below OFF'.format(deg(g['SLOPE_ON']), deg(g['SLOPE_OFF'])),
        'const float SIM_BEND_ON_DEG = {}, SIM_BEND_OFF_DEG = {};     // crest / valley above ON, left below OFF'.format(deg(g['BEND_ON']), deg(g['BEND_OFF'])),
        'const unsigned long SIM_MIN_DWELL_MS = {};   // a gait is kept this long before it may change'.format(int(round(g['MIN_DWELL'] * 1000))),
        '',
        'static const SimGaitTable SIM_GAIT_TABLES[] = {',
    ]
    for config, table in g['GAITS'].items():
        unknown = set(table) - set(SITUATIONS)
        if unknown:
            raise SystemExit('{}: situation(s) {} are not known to the firmware'.format(config, ', '.join(sorted(unknown))))
        lines.append('  {{"{}", {{'.format(config))
        for situation in SITUATIONS:
            if situation in table:
                params = dict(offset_p=0.0, offset_y=0.0)
                params.update(table[situation])
                lines.append('    {{true, {}}},   // {}'.format(', '.join(deg(params[k]) for k in KEYS), situation))
            else:
                lines.append('    {{false, 0, 0, 0, 0, 0, 0, 0}},   // {} (none)'.format(situation))
        lines.append('  }},')
    lines.append('};')
    lines.append('const int SIM_GAIT_TABLE_COUNT = {};'.format(len(g['GAITS'])))
    return '\n'.join(lines) + '\n'


def main():
    text = header()
    old = open(OUTPUT, encoding='utf-8').read() if os.path.exists(OUTPUT) else None
    if old == text:
        print('up to date', os.path.relpath(OUTPUT, ROOT))
        return
    with open(OUTPUT, 'w', encoding='utf-8', newline='\n') as out:
        out.write(text)
    print('wrote', os.path.relpath(OUTPUT, ROOT))


if __name__ == '__main__':
    main()
